"""Regression: with Claude data only, costs and counts must stay identical.

The golden `fixtures/claude_golden.json` was generated by the code before the 1.0 rework,
on these same synthetic fixtures. Routes that 1.0 replaced are rebuilt here from the new
ones, and the test compares everything with the golden: every key present in the golden must
have the same value (exact equality, floats included); new keys (for example `by_provider`)
are allowed. `python tests/server/test_regression_claude.py --write-golden` rewrites the
golden from the current code: use it only when a change in the numbers is intended.
"""

from __future__ import annotations

import json
import random
import sqlite3
import sys
from datetime import date
from pathlib import Path
from typing import Any, cast

from fastapi.testclient import TestClient

from ccmeter.server.app import create_app
from ccmeter.server.db import connect_db, ingest_batch, initialize_schema, reprocess_raw_lines
from ccmeter.server.pricing import BUNDLED_PRICES_PATH
from ccmeter.server.report import build_report

FIXTURES_DIR = Path(__file__).parents[1] / "fixtures"
GOLDEN_PATH = FIXTURES_DIR / "claude_golden.json"
PRICES_PATH = BUNDLED_PRICES_PATH
SYNTH_MODELS = (
    "claude-fable-5",
    "claude-fable-5-1",
    "claude-opus-4-8",
    "claude-opus-5-5",
    "claude-sonnet-5",
    "claude-haiku-4-5-20251001",
    "<synthetic>",
    "claude-invented-model-9",
)


def _fixture_lines(name: str) -> list[str]:
    return (FIXTURES_DIR / name).read_text(encoding="utf-8").splitlines()


def _existing_fixture_batches() -> list[tuple[str, list[dict[str, str]]]]:
    project = "C--work-demo-app"
    files = {
        "main_session_extract.jsonl": f"{project}/session.jsonl",
        "subagent_extract.jsonl": f"{project}/session/subagents/agent-a1097c2b70a1dff39.jsonl",
        "synthetic_extract.jsonl": f"{project}/session.jsonl",
        "duplicate_message_id_extract.jsonl": f"{project}/dup.jsonl",
        "prompt_sequence_extract.jsonl": f"{project}/prompts.jsonl",
        "workflow_journal_extract.jsonl": f"{project}/workflow.jsonl",
        "ignored_types_extract.jsonl": f"{project}/ignored.jsonl",
    }
    batch = [
        {"file": file_path, "line": line}
        for name, file_path in files.items()
        for line in _fixture_lines(name)
    ]
    return [("desktop", batch)]


def _usage(rng: random.Random) -> dict[str, Any]:
    usage: dict[str, Any] = {
        "input_tokens": rng.randint(0, 40_000),
        "output_tokens": rng.randint(1, 12_000),
        "cache_read_input_tokens": rng.randint(0, 900_000),
    }
    style = rng.randint(0, 2)
    if style == 0:
        usage["cache_creation"] = {
            "ephemeral_5m_input_tokens": rng.randint(0, 30_000),
            "ephemeral_1h_input_tokens": rng.randint(0, 30_000),
        }
    elif style == 1:
        usage["cache_creation_input_tokens"] = rng.randint(0, 50_000)
    return usage


def _synthetic_batches() -> list[tuple[str, list[dict[str, str]]]]:
    """Made-up, deterministic Claude data: multiple hosts, models, days and subagents."""
    rng = random.Random(20261005)
    batches: dict[str, list[dict[str, str]]] = {"desktop": [], "laptop": []}
    for session_index in range(4):
        host = "desktop" if session_index % 2 == 0 else "laptop"
        session_id = f"00000000-0000-4000-8000-{session_index:012d}"
        project = f"C--work-demo-project-{session_index}"
        main_file = f"{project}/{session_id}.jsonl"
        for prompt_index in range(6):
            day = 1 + (session_index * 3 + prompt_index) % 9
            prompt_id = f"prompt-{session_index}-{prompt_index}"
            hour_prefix = f"2026-07-{day:02d}T{8 + prompt_index:02d}"
            base_ts = f"{hour_prefix}:00:00.000Z"
            user = {
                "type": "user",
                "sessionId": session_id,
                "uuid": f"u-{session_index}-{prompt_index}",
                "timestamp": base_ts,
                "isSidechain": False,
                "promptId": prompt_id,
                "message": {"role": "user", "content": "invented text"},
            }
            batches[host].append({"file": main_file, "line": json.dumps(user)})
            for message_index in range(rng.randint(1, 4)):
                model = rng.choice(SYNTH_MODELS)
                message_id = f"msg_{session_index}_{prompt_index}_{message_index}"
                usage_data = _usage(rng)
                uuid = f"a-{session_index}-{prompt_index}-{message_index}"
                line: dict[str, Any] = {
                    "type": "assistant",
                    "sessionId": session_id,
                    "uuid": uuid,
                    "timestamp": f"{hour_prefix}:{message_index:02d}:30.000Z",
                    "isSidechain": False,
                    "promptId": prompt_id,
                    "message": {"id": message_id, "model": model, "usage": usage_data},
                }
                batches[host].append({"file": main_file, "line": json.dumps(line)})
                if rng.random() < 0.3:
                    # streaming chunk of the same message with a larger output
                    line["uuid"] = uuid + "-bis"
                    usage_data["output_tokens"] += 777
                    batches[host].append({"file": main_file, "line": json.dumps(line)})
            if prompt_index % 2 == 1:
                agent_id = f"a{session_index}{prompt_index}f00d"
                sub_file = f"{project}/{session_id}/subagents/agent-{agent_id}.jsonl"
                for message_index in range(rng.randint(1, 3)):
                    line = {
                        "type": "assistant",
                        "sessionId": session_id,
                        "uuid": f"s-{session_index}-{prompt_index}-{message_index}",
                        "timestamp": f"{hour_prefix}:3{message_index}:00.000Z",
                        "isSidechain": True,
                        "agentId": agent_id,
                        "message": {
                            "id": f"msg_sub_{session_index}_{prompt_index}_{message_index}",
                            "model": rng.choice(SYNTH_MODELS[:6]),
                            "usage": _usage(rng),
                        },
                    }
                    batches[host].append({"file": sub_file, "line": json.dumps(line)})
    return list(batches.items())


def build_claude_db(db_path: Path) -> None:
    """Creates a DB with the existing Claude fixtures plus the made-up Claude data."""
    conn = connect_db(db_path)
    try:
        initialize_schema(conn)
        for host, batch in _existing_fixture_batches() + _synthetic_batches():
            ingest_batch(conn, host=host, batch=batch)
    finally:
        conn.close()


def _without_volatile(data: dict[str, Any]) -> dict[str, Any]:
    health = cast(dict[str, Any], data.get("health", {}))
    health.pop("last_ingest", None)
    data.pop("last_ingest_ts", None)
    return data


LEGACY_PERIOD_PATH = "/api/dashboard/sessions?from=2026-07-02&to=2026-07-07"
# Keys of the old `ccdata` payload that the server still produces. `days`, `totalCost`,
# `projectionMonth` and `cache` were derived values for a fixed 7-day window: the dashboard
# now derives them itself for any period, from the same per-day numbers.
LEGACY_CCDATA_KEYS = ("allDays", "models", "hosts", "rawUsage", "sessions", "subagents", "health")


def collect_outputs(db_path: Path) -> dict[str, Any]:
    """Every cost and count ccmeter exposes, in the shapes the golden file records.

    The old dashboard routes (`ccdata.js`, `/api/dashboard/sessions`) are gone: their payloads
    are rebuilt here from the routes that replaced them, so the golden still checks every
    number they carried.
    """
    client = TestClient(
        create_app(db_path=db_path, api_token="secret-token", prices_path=PRICES_PATH)
    )
    out: dict[str, Any] = {}
    for path in (
        "/api/summary",
        "/api/summary?host=desktop",
        "/api/summary?from=2026-07-03&to=2026-07-06",
        "/api/spend/daily",
        "/api/sessions",
        "/api/subagents",
        "/api/health",
    ):
        response = client.get(path)
        assert response.status_code == 200, path
        out[path] = _without_volatile(cast(dict[str, Any], response.json()))
    out[LEGACY_PERIOD_PATH] = _legacy_period_sessions(client, "from=2026-07-02&to=2026-07-07")
    sessions = cast(list[dict[str, Any]], out["/api/sessions"]["sessions"])
    for session in sorted(sessions, key=lambda item: str(item["session_id"])):
        path = f"/api/sessions/{session['session_id']}"
        out[path] = client.get(path).json()
    out["ccdata"] = _without_volatile(_legacy_ccdata(client))
    conn: sqlite3.Connection = connect_db(db_path)
    try:
        out["report"] = _report_numbers(_full_report(conn))
        result = reprocess_raw_lines(conn)
        out["reprocess"] = {
            "raw_lines": result.raw_lines,
            "parsed": result.parsed,
            "errors": result.errors,
            "messages": result.messages,
            "sessions": result.sessions,
            "duplicates": result.duplicates,
        }
        out["report_after_reprocess"] = _report_numbers(_full_report(conn))
    finally:
        conn.close()
    return json.loads(json.dumps(out))


def _legacy_period_sessions(client: TestClient, query: str) -> dict[str, Any]:
    """The old `/api/dashboard/sessions` payload, from session-list + session-detail."""
    sessions, subagents = _sessions_with_details(client, query)
    return {"sessions": sessions, "subagents": subagents}


def _legacy_ccdata(client: TestClient) -> dict[str, Any]:
    """The primary keys of the old `ccdata` payload, from the routes that replaced it."""
    overview = cast(dict[str, Any], client.get("/api/dashboard/overview").json())
    sessions, subagents = _sessions_with_details(client, "")
    return {
        "allDays": overview["days"],
        "models": overview["models"],
        "hosts": overview["hosts"],
        "rawUsage": overview["rawUsage"],
        "sessions": sessions,
        "subagents": subagents,
        "health": overview["health"],
    }


def _sessions_with_details(
    client: TestClient, query: str
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    listing = client.get(f"/api/dashboard/session-list?{query}")
    assert listing.status_code == 200
    sessions = cast(list[dict[str, Any]], listing.json()["sessions"])
    subagents: list[dict[str, Any]] = []
    for session in sessions:
        response = client.get(f"/api/dashboard/session-detail/{session['session_id']}?{query}")
        assert response.status_code == 200
        detail = cast(dict[str, Any], response.json())
        assert detail["session"] == session
        session["prompts"] = detail["prompts"]
        subagents.extend(cast(list[dict[str, Any]], detail["subagents"]))
    # the old payload sorted every subagent of the period by (key, session, model), then by
    # cost: rebuild the same order from the per-session lists
    subagents.sort(key=lambda item: (str(item["key"]), str(item["session"]), str(item["model"])))
    subagents.sort(key=lambda item: float(item["cost"]), reverse=True)
    return sessions, subagents


def _full_report(conn: sqlite3.Connection) -> str:
    """Report over a period that covers every message, like the old report always did."""
    first, last = conn.execute("SELECT MIN(ts), MAX(ts) FROM messages").fetchone()
    first_day = date.fromisoformat(str(first)[:10])
    last_day = date.fromisoformat(str(last)[:10])
    days = (last_day - first_day).days + 1
    return build_report(conn, prices_path=PRICES_PATH, days=days, today=last_day)


def _report_numbers(text: str) -> dict[str, Any]:
    """The numbers of a report, independent of its wording and language.

    The per-day/per-model and per-host lines keep the same format across versions; the
    header, the projection divisor and the labels changed on purpose.
    """
    lines = text.splitlines()
    cache = next(line for line in lines if line.startswith("Cache hit rate:"))
    unpriced = lines[-1].split(":", 1)[1].strip()
    return {
        "lines": [line for line in lines if line.startswith("- ")],
        "cache_hit_rate": cache,
        "unpriced": [] if unpriced in {"nessuno", "none"} else unpriced.split(", "),
    }


def _assert_subset(golden: object, current: object, path: str = "$") -> None:
    if isinstance(golden, dict):
        assert isinstance(current, dict), path
        golden_dict = cast(dict[str, object], golden)
        current_dict = cast(dict[str, object], current)
        for key, value in golden_dict.items():
            assert key in current_dict, f"{path}.{key} mancante"
            _assert_subset(value, current_dict[key], f"{path}.{key}")
        return
    if isinstance(golden, list):
        assert isinstance(current, list), path
        golden_list = cast(list[object], golden)
        current_list = cast(list[object], current)
        assert len(golden_list) == len(current_list), f"{path}: different length"
        for index, (left, right) in enumerate(zip(golden_list, current_list, strict=True)):
            _assert_subset(left, right, f"{path}[{index}]")
        return
    assert golden == current, f"{path}: {golden!r} != {current!r}"


def test_claude_costs_and_counts_identical_to_base(tmp_path: Path) -> None:
    db_path = tmp_path / "ccmeter.db"
    build_claude_db(db_path)

    current = collect_outputs(db_path)

    golden = cast(dict[str, Any], json.loads(GOLDEN_PATH.read_text(encoding="utf-8")))
    golden["ccdata"] = {
        key: value
        for key, value in cast(dict[str, Any], golden["ccdata"]).items()
        if key in LEGACY_CCDATA_KEYS
    }
    for key in ("report", "report_after_reprocess"):
        if isinstance(golden[key], str):
            golden[key] = _report_numbers(cast(str, golden[key]))
    _assert_subset(golden, current)


if __name__ == "__main__" and "--write-golden" in sys.argv:
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        target = Path(tmp) / "ccmeter.db"
        build_claude_db(target)
        payload = collect_outputs(target)
    with GOLDEN_PATH.open("w", encoding="utf-8", newline="\n") as handle:
        json.dump(payload, handle, indent=1, sort_keys=True)
        handle.write("\n")
    print("golden written:", GOLDEN_PATH)
